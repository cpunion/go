// emitCallableAdapter emits a tiny typed factory adapter for a lowered method
// or top-level function so dynamic interface/function `go` calls can dispatch
// directly into F.coro with zero argument boxing and zero allocation.
func (p *Plan) emitCallableAdapter(info *FuncInfo) {
	fn := info.Orig
	if fn.OClosure != nil {
		return // anonymous closures are dispatched directly at their literal site
	}
	pos := fn.Pos()
	sig := fn.Type()
	resumeFuncType := info.FactoryFn.Type().Results()[1].Type

	// Adapter signature:
	//   func(recvOrClo unsafe.Pointer, args...) (unsafe.Pointer, func(unsafe.Pointer) uint8)
	var params []*types.Field
	params = append(params, types.NewField(pos, types.LocalPkg.Lookup("raw"), types.Types[types.TUNSAFEPTR]))
	for i, pf := range sig.Params() {
		params = append(params, types.NewField(pos, types.LocalPkg.Lookup(fmt.Sprintf("a%d", i)), pf.Type))
	}
	results := []*types.Field{
		types.NewField(pos, nil, types.Types[types.TUNSAFEPTR]),
		types.NewField(pos, nil, resumeFuncType),
	}
	adpSig := types.NewSignature(nil, params, results)

	if recv := sig.Recv(); recv != nil {
		// Method adapter (supports pointer receivers directly; value receivers dereference *T).
		adpSym := types.LocalPkg.Lookup(fn.Sym().Name + ".coro.iface")
		adp := ir.NewFunc(pos, pos, adpSym, adpSig)
		typecheck.DeclFunc(adp)
		ir.WithFunc(adp, func() {
			adpParams := adp.Type().Params()
			raw := adpParams[0].Nname.(*ir.Name)
			var callArgs []ir.Node
			if recv.Type.IsPtr() {
				callArgs = append(callArgs, typecheck.ConvNop(raw, recv.Type))
			} else {
				callArgs = append(callArgs, typecheck.Expr(ir.NewStarExpr(pos, typecheck.ConvNop(raw, types.NewPtr(recv.Type)))))
			}
			for i := 1; i < len(adpParams); i++ {
				callArgs = append(callArgs, adpParams[i].Nname.(*ir.Name))
			}
			facCall := typecheck.Call(pos, info.FactoryFn.Nname, callArgs, false)
			adp.Body.Append(typecheck.Stmt(ir.NewReturnStmt(pos, []ir.Node{facCall})))
			typecheck.FinishFuncBody()
			typecheck.Stmts(adp.Body)
		})
		info.IfaceAdpFn = adp
		return
	}

	// Top-level function adapter: ignores raw closure pointer and forwards args to F.coro.
	adpSym := types.LocalPkg.Lookup(fn.Sym().Name + ".coro.fn")
	adp := ir.NewFunc(pos, pos, adpSym, adpSig)
	typecheck.DeclFunc(adp)
	ir.WithFunc(adp, func() {
		adpParams := adp.Type().Params()
		var callArgs []ir.Node
		for i := 1; i < len(adpParams); i++ {
			callArgs = append(callArgs, adpParams[i].Nname.(*ir.Name))
		}
		facCall := typecheck.Call(pos, info.FactoryFn.Nname, callArgs, false)
		adp.Body.Append(typecheck.Stmt(ir.NewReturnStmt(pos, []ir.Node{facCall})))
		typecheck.FinishFuncBody()
		typecheck.Stmts(adp.Body)
	})
	info.FuncAdpFn = adp
}

// emitCallableInit creates a synthetic package init function calling
// runtime.coroRegisterCallable for every lowered method/function in this package.
func (p *Plan) emitCallableInit(lowered []*FuncInfo) {
	var regs []*FuncInfo
	for _, info := range lowered {
		if info.IfaceAdpFn != nil || info.FuncAdpFn != nil {
			regs = append(regs, info)
		}
	}
	if len(regs) == 0 {
		return
	}

	pos := base.AutogeneratedPos
	sym := noder.Renameinit()
	fnInit := ir.NewFunc(pos, pos, sym, types.NewSignature(nil, nil, nil))
	typecheck.DeclFunc(fnInit)
	ir.WithFunc(fnInit, func() {
		regFn := typecheck.LookupRuntime("coroRegisterCallable")
		for _, info := range regs {
			fn := info.Orig
			if info.IfaceAdpFn != nil {
				// Method expression (*T).M (or T.M) gives a direct funcval whose .fn matches itab.Fun[idx].
				recv := fn.Type().Recv()
				mname := methodBaseName(fn)
				if mname == "" {
					continue
				}
				msym := fn.Sym().Pkg.Lookup(mname)
				mexpr := typecheck.NewMethodExpr(pos, recv.Type, msym)
				if mexpr == nil {
					continue
				}
				fnAny := typecheck.AssignConv(mexpr, types.Types[types.TINTER], "coroRegisterCallable")
				facAny := typecheck.AssignConv(info.IfaceAdpFn.Nname, types.Types[types.TINTER], "coroRegisterCallable")
				fnInit.Body.Append(typecheck.Stmt(typecheck.Call(pos, regFn, []ir.Node{fnAny, facAny}, false)))
			} else if info.FuncAdpFn != nil {
				fnAny := typecheck.AssignConv(fn.Nname, types.Types[types.TINTER], "coroRegisterCallable")
				facAny := typecheck.AssignConv(info.FuncAdpFn.Nname, types.Types[types.TINTER], "coroRegisterCallable")
				fnInit.Body.Append(typecheck.Stmt(typecheck.Call(pos, regFn, []ir.Node{fnAny, facAny}, false)))
			}
		}
		typecheck.FinishFuncBody()
		typecheck.Stmts(fnInit.Body)
	})
	p.Pkg.Inits = append(p.Pkg.Inits, fnInit)
}

func methodBaseName(fn *ir.Func) string {
	if fn.Sym() == nil {
		return ""
	}
	name := fn.Sym().Name
	for i := len(name) - 1; i >= 0; i-- {
		if name[i] == '.' {
			return name[i+1:]
		}
	}
	return ""
}

// emitDynamicInterfaceGo lowers `go iface.M(args...)` using runtime.coroLookupInterface
// + direct typed adapter invocation + runtime.coroSpawnFrame (with coroSpawnOpaque fallback).
func (rw *bodyRewriter) emitDynamicInterfaceGo(pos src.XPos, call *ir.CallExpr) {
	sel := call.Fun.(*ir.SelectorExpr)
	ifaceExpr := rw.rewriteNode(sel.X)
	ifaceVar := newLocal(rw.rf, pos, fmt.Sprintf(".di%d", rw.tmpSeq), ifaceExpr.Type())
	rw.rf.Body.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, ifaceVar)))
	rw.rf.Body.Append(assignNode(pos, ifaceVar, ifaceExpr))

	// Evaluate arguments once per Go spec.
	argVars := make([]*ir.Name, len(call.Args))
	for i, a := range call.Args {
		ra := rw.rewriteNode(a)
		av := newLocal(rw.rf, pos, fmt.Sprintf(".da%d_%d", rw.tmpSeq, i), ra.Type())
		rw.rf.Body.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, av)))
		rw.rf.Body.Append(assignNode(pos, av, ra))
		argVars[i] = av
	}
	seq := rw.tmpSeq
	rw.tmpSeq++

	// facPtr, recvPtr := runtime.coroLookupInterface(itab(ifaceVar), idata(ifaceVar), methodIdx)
	itabRaw := ir.NewUnaryExpr(pos, ir.OITAB, ifaceVar)
	itabRaw.SetType(types.Types[types.TUINTPTR])
	itabRaw.SetTypecheck(1)
	itabNode := typecheck.ConvNop(itabRaw, types.Types[types.TUNSAFEPTR])
	idataNode := ir.NewUnaryExpr(pos, ir.OIDATA, ifaceVar)
	idataNode.SetType(types.Types[types.TUNSAFEPTR])
	idataNode.SetTypecheck(1)
	methodIdx := sel.Offset() / int64(types.PtrSize)
	idxNode := typecheck.Conv(ir.NewInt(pos, methodIdx), types.Types[types.TUINTPTR])

	facPtr := newLocal(rw.rf, pos, fmt.Sprintf(".fp%d", seq), types.Types[types.TUNSAFEPTR])
	recvPtr := newLocal(rw.rf, pos, fmt.Sprintf(".rp%d", seq), types.Types[types.TUNSAFEPTR])
	lkCall := typecheck.Call(pos, typecheck.LookupRuntime("coroLookupInterface"), []ir.Node{itabNode, idataNode, idxNode}, false)
	rw.rf.Body.Append(typecheck.Stmt(ir.NewAssignListStmt(pos, ir.OAS2, []ir.Node{facPtr, recvPtr}, []ir.Node{lkCall})))

	// Construct typed adapter func type: func(unsafe.Pointer, argTypes...) (unsafe.Pointer, func(unsafe.Pointer) uint8)
	adpType := buildDynamicAdapterType(pos, call.Fun.Type())

	// Fast branch: if facPtr != nil { cast facPtr to adpType, call, coroSpawnFrame }
	var thenBody ir.Nodes
	facFnVar := newLocal(rw.rf, pos, fmt.Sprintf(".ff%d", seq), adpType)
	thenBody.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, facFnVar)))
	thenBody.Append(assignNode(pos, facFnVar, ir.NewNilExpr(pos, adpType)))
	// *(*unsafe.Pointer)(unsafe.Pointer(&facFnVar)) = facPtr
	dstPtr := typecheck.ConvNop(typecheck.NodAddrAt(pos, facFnVar), types.NewPtr(types.Types[types.TUNSAFEPTR]))
	thenBody.Append(assignNode(pos, typecheck.Expr(ir.NewStarExpr(pos, dstPtr)), facPtr))

	callArgs := make([]ir.Node, 0, 1+len(argVars))
	callArgs = append(callArgs, recvPtr)
	for _, av := range argVars {
		callArgs = append(callArgs, av)
	}
	frameVar := newLocal(rw.rf, pos, fmt.Sprintf(".sf%d", seq), types.Types[types.TUNSAFEPTR])
	resVar := newLocal(rw.rf, pos, fmt.Sprintf(".sr%d", seq), adpType.Results()[1].Type)
	adpCall := typecheck.Call(pos, facFnVar, callArgs, false)
	thenBody.Append(typecheck.Stmt(ir.NewAssignListStmt(pos, ir.OAS2, []ir.Node{frameVar, resVar}, []ir.Node{adpCall})))
	thenBody.Append(typecheck.Stmt(typecheck.Call(pos, typecheck.LookupRuntime("coroSpawnFrame"), []ir.Node{rw.ctxVar, frameVar, resVar}, false)))

	// Fallback branch: coroSpawnOpaque(ctx, func() { ifaceVar.M(argVars...) })
	thunk := rw.makeZeroArgThunk(pos, func(clo *ir.Func) {
		ci := ir.NewClosureVar(pos, clo, ifaceVar)
		csel := ir.NewSelectorExpr(pos, ir.ODOTINTER, ci, sel.Sel)
		csel.Selection = sel.Selection
		csel.SetType(sel.Type())
		csel.SetTypecheck(1)
		cArgs := make([]ir.Node, len(argVars))
		for i, av := range argVars {
			cArgs[i] = ir.NewClosureVar(pos, clo, av)
		}
		ce := typecheck.Call(pos, csel, cArgs, call.IsDDD)
		clo.Body.Append(typecheck.Stmt(ce))
	})
	elseBody := []ir.Node{
		typecheck.Stmt(typecheck.Call(pos, typecheck.LookupRuntime("coroSpawnOpaque"), []ir.Node{rw.ctxVar, thunk}, false)),
	}

	cond := typecheck.Expr(ir.NewBinaryExpr(pos, ir.ONE, facPtr, ir.NewNilExpr(pos, types.Types[types.TUNSAFEPTR])))
	rw.rf.Body.Append(typecheck.Stmt(ir.NewIfStmt(pos, cond, thenBody, elseBody)))
}

// emitDynamicFuncGo lowers `go fnVar(args...)` using runtime.coroLookupFunction
// + direct typed adapter invocation + runtime.coroSpawnFrame (with coroSpawnOpaque fallback).
func (rw *bodyRewriter) emitDynamicFuncGo(pos src.XPos, call *ir.CallExpr) {
	fnExpr := rw.rewriteNode(call.Fun)
	fnVar := newLocal(rw.rf, pos, fmt.Sprintf(".df%d", rw.tmpSeq), fnExpr.Type())
	rw.rf.Body.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, fnVar)))
	rw.rf.Body.Append(assignNode(pos, fnVar, fnExpr))

	argVars := make([]*ir.Name, len(call.Args))
	for i, a := range call.Args {
		ra := rw.rewriteNode(a)
		av := newLocal(rw.rf, pos, fmt.Sprintf(".da%d_%d", rw.tmpSeq, i), ra.Type())
		rw.rf.Body.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, av)))
		rw.rf.Body.Append(assignNode(pos, av, ra))
		argVars[i] = av
	}
	seq := rw.tmpSeq
	rw.tmpSeq++

	facPtr := newLocal(rw.rf, pos, fmt.Sprintf(".fp%d", seq), types.Types[types.TUNSAFEPTR])
	cloPtr := newLocal(rw.rf, pos, fmt.Sprintf(".cp%d", seq), types.Types[types.TUNSAFEPTR])
	fnAny := typecheck.AssignConv(fnVar, types.Types[types.TINTER], "coroLookupFunction")
	lkCall := typecheck.Call(pos, typecheck.LookupRuntime("coroLookupFunction"), []ir.Node{fnAny}, false)
	rw.rf.Body.Append(typecheck.Stmt(ir.NewAssignListStmt(pos, ir.OAS2, []ir.Node{facPtr, cloPtr}, []ir.Node{lkCall})))

	adpType := buildDynamicAdapterType(pos, fnVar.Type())

	var thenBody ir.Nodes
	facFnVar := newLocal(rw.rf, pos, fmt.Sprintf(".ff%d", seq), adpType)
	thenBody.Append(typecheck.Stmt(ir.NewDecl(pos, ir.ODCL, facFnVar)))
	thenBody.Append(assignNode(pos, facFnVar, ir.NewNilExpr(pos, adpType)))
	dstPtr := typecheck.ConvNop(typecheck.NodAddrAt(pos, facFnVar), types.NewPtr(types.Types[types.TUNSAFEPTR]))
	thenBody.Append(assignNode(pos, typecheck.Expr(ir.NewStarExpr(pos, dstPtr)), facPtr))

	callArgs := make([]ir.Node, 0, 1+len(argVars))
	callArgs = append(callArgs, cloPtr)
	for _, av := range argVars {
		callArgs = append(callArgs, av)
	}
	frameVar := newLocal(rw.rf, pos, fmt.Sprintf(".sf%d", seq), types.Types[types.TUNSAFEPTR])
	resVar := newLocal(rw.rf, pos, fmt.Sprintf(".sr%d", seq), adpType.Results()[1].Type)
	adpCall := typecheck.Call(pos, facFnVar, callArgs, false)
	thenBody.Append(typecheck.Stmt(ir.NewAssignListStmt(pos, ir.OAS2, []ir.Node{frameVar, resVar}, []ir.Node{adpCall})))
	thenBody.Append(typecheck.Stmt(typecheck.Call(pos, typecheck.LookupRuntime("coroSpawnFrame"), []ir.Node{rw.ctxVar, frameVar, resVar}, false)))

	thunk := rw.makeZeroArgThunk(pos, func(clo *ir.Func) {
		cf := ir.NewClosureVar(pos, clo, fnVar)
		cArgs := make([]ir.Node, len(argVars))
		for i, av := range argVars {
			cArgs[i] = ir.NewClosureVar(pos, clo, av)
		}
		ce := typecheck.Call(pos, cf, cArgs, call.IsDDD)
		clo.Body.Append(typecheck.Stmt(ce))
	})
	elseBody := []ir.Node{
		typecheck.Stmt(typecheck.Call(pos, typecheck.LookupRuntime("coroSpawnOpaque"), []ir.Node{rw.ctxVar, thunk}, false)),
	}

	cond := typecheck.Expr(ir.NewBinaryExpr(pos, ir.ONE, facPtr, ir.NewNilExpr(pos, types.Types[types.TUNSAFEPTR])))
	rw.rf.Body.Append(typecheck.Stmt(ir.NewIfStmt(pos, cond, thenBody, elseBody)))
}

func buildDynamicAdapterType(pos src.XPos, callSig *types.Type) *types.Type {
	params := []*types.Field{types.NewField(pos, nil, types.Types[types.TUNSAFEPTR])}
	for _, p := range callSig.Params() {
		params = append(params, types.NewField(pos, nil, p.Type))
	}
	resumeSig := types.NewSignature(nil,
		[]*types.Field{types.NewField(pos, nil, types.Types[types.TUNSAFEPTR])},
		[]*types.Field{types.NewField(pos, nil, types.Types[types.TUINT8])},
	)
	results := []*types.Field{
		types.NewField(pos, nil, types.Types[types.TUNSAFEPTR]),
		types.NewField(pos, nil, resumeSig),
	}
	return types.NewSignature(nil, params, results)
}
